def _load_tonc_bits() -> bytes:
    """The authoritative bytes: read straight from a freshly re-extracted copy
    of libtonc's toncfont.o .rodata section when the toolchain is available (so
    a stale hex literal can never silently drift from the linked font), else
    fall back to the frozen TONC_SYS8_HEX literal above (offline / no
    devkitARM -- host tests must still run)."""
    import shutil
    import subprocess
    import tempfile

    libtonc_a = Path("/opt/devkitpro/libtonc/lib/libtonc.a")
    objcopy = shutil.which("arm-none-eabi-objcopy") or "/opt/devkitpro/devkitARM/bin/arm-none-eabi-objcopy"
    ar = shutil.which("arm-none-eabi-ar") or "/opt/devkitpro/devkitARM/bin/arm-none-eabi-ar"
    if libtonc_a.is_file() and Path(objcopy).exists() and Path(ar).exists():
        try:
            with tempfile.TemporaryDirectory() as td:
                tdp = Path(td)
                subprocess.run([ar, "x", str(libtonc_a), "toncfont.o"], cwd=tdp,
                                check=True, capture_output=True)
                subprocess.run([objcopy, "-O", "binary", "--only-section=.rodata",
                                 "toncfont.o", "sys8font.bin"], cwd=tdp,
                                check=True, capture_output=True)
                data = (tdp / "sys8font.bin").read_bytes()
                if len(data) == NUM_GLYPHS * GLYPH_ROWS:
                    return data
        except (OSError, subprocess.CalledProcessError, AssertionError):
            pass  # no toolchain / no objcopy here: fall through to the frozen literal
    return bytes.fromhex(TONC_SYS8_HEX)


