"""tools/gb_claims.py -- mechanically verify a shot's caption against its own pixels
(BACKLOG #184).

WHY THIS EXISTS
----------------
Three rounds and ~900k tokens went on captions describing frames nobody had looked at
(BACKLOG #198). A caption is a CLAIM about pixels; this module turns "the frame shows
X" into a check a machine can run: render the string X the same way PokeDNA's own UI
code renders it, then search the frame PNG for a pixel-exact match. No OCR, no
ML -- exact bitmap search against PokeDNA's own two font sources.

TWO FONT SOURCES, TWO RENDER MODES
-----------------------------------
PokeDNA draws text through exactly two code paths (source/ui.c):

  ui_ptext()/ui_ptext_fit()/... -- OUR OWN proportional 5x7 face, `ui_font_bits`
    (source/ui_font.c, GENERATED by tools/gen_font.py, not ROM-derived). Row bytes,
    bit 0 = LEFTMOST pixel (ui_font.c's own header comment; verified against the
    blitter below). Advance per glyph is `ui_font_w[i]` = ink width + 1px gap
    (ui.c:8's comment, matches PADV()/ui_ptext's `x += PADV(c)` at ui.c:357).
    render(text, proportional=True) reproduces this.

  ui_text()/ui_text_sel() -- tonc's OWN "sys8Font" via tte_set_pos()+tte_write()
    (ui.c:75-86). This is NOT ui_font_bits -- it is a separate, fixed-width 8x8
    bitmap baked into libtonc (declared `extern const TFont sys8Font` in
    tonc_tte.h:339, documented there as "FWF 8x8@1" -- Fixed-Width Font, 8 pixels
    wide, 1 bit per pixel, space(0x20)..127, the identical 96-glyph range
    ui_font_bits covers). libtonc ships this font only as compiled object code
    (toncfont.o inside lib/libtonc.a's .rodata, symbol `toncfontTiles`) -- there
    is no C source in the devkitPro tree to parse the way ui_font.c is parsed
    below. TONC_SYS8_BITS is that SAME 768-byte table (96 glyphs x 8 rows),
    extracted once with `arm-none-eabi-objcopy -O binary --only-section=.rodata`
    against /opt/devkitpro/libtonc/lib/libtonc.a's toncfont.o member and frozen
    here as a hex literal -- it is libtonc's own font data (already linked into
    every PokeDNA build; WTFPL-licensed upstream, not ROM/game-derived), read
    straight out of the toolchain PokeDNA already builds with, not out of any
    Nintendo ROM. Bit order is the same convention tonc documents for its own
    sys8 (ui_font.c's header comment cites it directly: "same order as tonc's
    sys8"). Advance is FIXED at 8 px (no per-glyph width table for this font --
    TFont.widths is NULL for sys8Font, so tte falls back to `font->charW`, tonc's
    own 8px cell -- tonc_tte.h's TTE_CHAR_VARS macro, `font->widths ? ... :
    font->charW`).
    render(text, proportional=False) reproduces this.

  render(text, proportional=None) is not a third mode -- callers needing "try
  both, whichever matches" call find() with proportional=None (below), which
  tries both renderers rather than guessing.

RENDER
------
render() returns an (8, total_width) bool numpy array: True = ink pixel. Each
glyph is placed at consecutive columns; the inter-glyph GAP is included in the
array as False columns (both the ink test on that glyph's own trailing gap
columns AND the leading columns before the next glyph read 0) -- so a caller
searching for this exact bitmap in a frame requires the gap pixels to be
NON-ink too, not merely "don't care". This is deliberate (see find()'s
docstring) -- it is what "the frame shows this text" should mean pixel for
pixel, given both PokeDNA fonts never draw anything into the gap.

FIND
----
find(frame_png, text, proportional=None) treats the frame as a stack of binary
planes, one per distinct colour present, and slides the rendered mask over
each plane with numpy.lib.stride_tricks.sliding_window_view, looking for an
EXACT match (every ink pixel of the mask equals that colour, every
gap/background pixel of the mask's footprint does NOT). Text colour is not
known a priori (menus, footers, selected-row inverse video, and the HOF
crystal-card panel all use different ink colours) -- trying every distinct
colour in the frame is the only caller-agnostic way to find it. A
drop-shadow/outline variant (ui_ptext_shadow, ui.c:439-441, draws the SAME
string twice at a 1px offset in two different colours) still matches on its
own main-ink colour plane: the shadow copy is a different colour, so it is
invisible on the main colour's binary plane except where it happens to
overlap real background pixels of that colour, which the exact-gap-match
requirement then rejects same as any other stray ink.

A normal GBA UI capture is indexed 15-bit colour and never has more than a
few dozen distinct RGB values, but a sprite/gameplay frame (icons, box art,
dithered gradients) can legitimately exceed 256 -- BACKLOG #214. Raising in
that case turned "this claim doesn't hold on this kind of frame" into a
crash that aborted the whole runner instead of a normal `[CLAIM FAILED]`.
find() therefore never raises on colour count: it bounds the search to the
MAX_COLOURS_SCANNED most FREQUENT colours in the frame (by pixel count).
Rendered text is always a solid run of many same-coloured ink pixels (a
"text-sized run"), so its ink colour is high-frequency even against a busy
sprite frame's many low-frequency (often singleton) art colours; this is a
bounded per-colour search over the most-frequent colours, not quantisation,
so it never distorts the exact bitmap match. When the frame has
<=MAX_COLOURS_SCANNED colours this is exactly the old exhaustive search
(every colour is "most frequent" by definition); above the cap it is a
best-effort search that can miss a low-frequency ink colour, which is
reported as an ordinary empty result (claim failure), never an exception.
"""
