/*
 * art_fallbacks.c — weak defaults that make the ZERO-ART build a real product.
 *
 * Guy's bar (2026-08-08): the artless PokeDNA is the product; registering your own
 * retail ROM is a nice addition, not a must. So a clone with NO generated art must
 * compile, link, boot, and look intentional. Every generated art module's strong
 * symbols (mon_icons*.c, item_icons.c, type_icons.c, hand_oam.c, mon_front/back.c)
 * simply override these at link time; when they are absent, these take over:
 *
 *   - every icon/sprite accessor returns NULL/0 and the screens keep their text
 *     layouts (the long-standing art-free convention);
 *   - the PC cursor is an ORIGINAL arrow pointer, drawn as ASCII art below and
 *     converted to 4bpp tiles — nothing traced from any ROM or decomp, same
 *     provenance rule as the 5x7 font in tools/gen_font.py.
 *
 * ui_sprite() already ignores NULL, so passing a fallback result straight through
 * is safe everywhere.
 */
